import { fileURLToPath, URL } from 'node:url'
import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'
import tailwindcss from '@tailwindcss/vite'

export default defineConfig({
  plugins: [vue(), tailwindcss()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    host: true,
    port: 5173,
    // Poll for file changes: fsnotify/inotify events don't reliably cross bind
    // mounts on macOS/Windows Docker, so polling keeps HMR working everywhere.
    watch: {
      usePolling: true,
      interval: 300,
    },
    // Proxy API calls to the Go backend so the browser sees a single origin.
    proxy: {
      '/api': {
        target: process.env.VITE_API_PROXY_TARGET || 'http://localhost:8080',
        changeOrigin: true,
      },
    },
  },
})
